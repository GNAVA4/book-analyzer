from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING


def setup_styles(doc):
    """Базовые настройки документа под формат курсовой/ВКР."""
    style = doc.styles['Normal']
    style.font.name = 'Times New Roman'
    style.font.size = Pt(14)
    pf = style.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.first_line_indent = Cm(1.25)
    pf.space_after = Pt(0)
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def set_margins(doc):
    """Поля по ГОСТу для ВКР."""
    for section in doc.sections:
        section.top_margin = Cm(2.0)
        section.bottom_margin = Cm(2.0)
        section.left_margin = Cm(3.0)
        section.right_margin = Cm(1.5)


def add_heading(doc, text, level=1, center=False):
    """Заголовок главы. level=1 — большой, level=2 — подраздел."""
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(16 if level == 1 else 14)
    run.font.name = 'Times New Roman'


def add_para(doc, text, bold=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    if bold:
        run.bold = True
    return p


def add_bullet(doc, text):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.left_indent = Cm(1.25)
    run = p.runs[0] if p.runs else p.add_run(text)
    if not p.runs:
        p.add_run(text)
    for r in p.runs:
        r.font.name = 'Times New Roman'
        r.font.size = Pt(14)
    return p


def add_code_para(doc, text):
    """Короткий моноширинный фрагмент (имя файла, функции)."""
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.left_indent = Cm(1.25)
    run = p.add_run(text)
    run.font.name = 'Consolas'
    run.font.size = Pt(11)


def page_break(doc):
    doc.add_page_break()


